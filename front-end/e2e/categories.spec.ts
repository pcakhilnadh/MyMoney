import { expect, test } from '@playwright/test'
import { fakeSignIn } from './helpers'

test('category types, hiding, and expense-only budgets', async ({ page }) => {
  await page.route('**/auth/refresh', (route) => route.abort())
  await page.route('**/auth/login', (route) => route.abort())
  await fakeSignIn(page, {
    sub: 'category-user',
    email: 'category@gmail.com',
    name: 'Category User',
  })

  await page.goto('/settings/categories')
  await expect(page.getByText('Food & Dining')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Delete Food & Dining' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Hide Food & Dining' }).click()
  await expect(page.getByText('Default · Hidden')).toBeVisible()

  await page.goto('/expenses/new')
  const categoryButtons = page.getByRole('group', { name: 'Category' }).getByRole('button')
  const categoryNames = await categoryButtons.allTextContents()
  expect(categoryNames).toEqual([...categoryNames].sort((a, b) => a.localeCompare(b)))
  await page.getByRole('button', { name: 'Refund' }).click()
  await expect(page.getByText('Expense category')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Food & Dining' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Shopping' })).toBeVisible()

  await page.getByRole('button', { name: 'Income' }).click()
  await expect(page.getByRole('button', { name: 'Salary' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Shopping' })).toHaveCount(0)

  await page.getByRole('button', { name: 'Transfer' }).click()
  await expect(page.getByRole('button', { name: 'Money Lent' })).toBeVisible()

  await page.goto('/settings/categories')
  await page.getByRole('button', { name: 'Add category' }).click()
  await expect(page.getByPlaceholder('New expense category')).toBeVisible()
  await page.getByPlaceholder('New expense category').fill('Test category')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(page.getByText('Test category')).toBeVisible()

  await page.goto('/expenses/new')
  await page.getByRole('link', { name: 'Add account' }).click()
  await page.getByRole('button', { name: 'Add payment account' }).click()
  await page.getByPlaceholder('Account name').fill('Category test account')
  await page.getByRole('button', { name: 'Add Account' }).click()
  await page.goBack()
  await page.getByLabel('Paid from').selectOption({ label: 'Category test account' })
  await page.getByLabel('Amount').fill('123.45')
  await page.getByPlaceholder('Title').fill('Test category expense')
  await page.getByRole('button', { name: 'Test category' }).click()
  await expect(page.getByRole('button', { name: 'Save Expense' })).toBeEnabled()
  await page.getByRole('button', { name: 'Save Expense' }).click()
  await expect(page).toHaveURL(/\/transactions/)
  await expect(page.getByText('Test category expense')).toBeVisible()

  await page.goto('/settings/categories')
  await page.getByRole('button', { name: 'Hide Test category' }).click()
  await expect(page.getByRole('button', { name: 'Show Test category' })).toBeVisible()
  await page.goto('/budgets')
  await expect(page.getByRole('button', { name: 'Add budget' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Food & Dining' })).toHaveCount(0)
  await expect(page.getByText('No budget set')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Test category' })).toBeVisible()
  await expect(page.getByRole('heading', { level: 2 }).first()).toHaveText('Test category')
  await expect(page.getByText('₹123.45 spent this month')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Set Test category budget' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Open Test category budget details' }).click()
  await expect(page.getByRole('heading', { name: 'Test category' })).toBeVisible()
  await expect(page.getByText('Spent this month')).toBeVisible()
  await expect(page.getByText('Remaining')).toBeVisible()
  await expect(page.getByText('—')).toBeVisible()
  await page.getByRole('button', { name: 'Set budget' }).click()
  const budgetAmount = page.getByLabel('Monthly limit')
  const saveBudget = page.getByRole('button', { name: 'Save Test category budget' })
  const amountBox = await budgetAmount.boundingBox()
  const saveBox = await saveBudget.boundingBox()
  expect(amountBox && saveBox).not.toBeNull()
  if (amountBox && saveBox) expect(amountBox.height).toBeCloseTo(saveBox.height, 0)
  await budgetAmount.fill('100')
  expect(await budgetAmount.evaluate((element) => getComputedStyle(element).fontSize)).toBe('12px')
  await saveBudget.click()
  await expect(page.getByText('₹100.00', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Transactions this month' })).toBeVisible()
  await page.getByRole('button', { name: /Expense: Test category expense/ }).click()
  await expect(page.getByRole('heading', { name: 'Test category expense' })).toBeVisible()
  await page.getByRole('link', { name: '← Category' }).click()
  await expect(page.getByRole('heading', { name: 'Transactions this month' })).toBeVisible()
  await page.goto('/budgets')
  await expect(page.getByRole('heading', { name: 'Test category' })).toBeVisible()
  await page.getByRole('link', { name: 'Open Test category budget details' }).click()
  await expect(page.getByText('Spent this month')).toBeVisible()
  await expect(page.getByText('Remaining')).toBeVisible()
  await expect(page.getByText('Monthly limit')).toBeVisible()
  await expect(page.getByText('₹100.00', { exact: true })).toBeVisible()
  await expect(page.getByText('₹123.45', { exact: true })).toBeVisible()
  await expect(page.getByText('Over budget by')).toBeVisible()
  await expect(page.getByRole('button', { name: /Expense: Test category expense/ })).toBeVisible()
  await page.getByRole('link', { name: '← Budgets' }).click()
  await expect(page.getByRole('heading', { name: 'Test category' })).toBeVisible()
  await expect(page.getByText('Available to spend')).toHaveCount(0)
  await expect(page.getByText('Over budget by')).toBeVisible()
  await expect(page.getByText('Monthly limit')).toBeVisible()
  await expect(page.getByText('100% used')).toBeVisible()
})
