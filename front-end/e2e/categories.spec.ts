import { expect, test } from '@playwright/test'
import { chooseCategory, chooseOption, fakeSignIn } from './helpers'

test('category types, hiding, and expense-only budgets', async ({ page }) => {
  await page.route('**/auth/refresh', (route) => route.abort())
  await page.route('**/auth/login', (route) => route.abort())
  await fakeSignIn(page, {
    sub: 'category-user',
    email: 'category@gmail.com',
    name: 'Category User',
  })

  await page.goto('/money/settings/categories')
  await expect(page.getByText('Food & Dining')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Delete Food & Dining' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Hide Food & Dining' }).click()
  await expect(page.getByText('Default · Hidden')).toBeVisible()

  await page.goto('/money/expenses/new')
  const category = page.getByRole('combobox', { name: 'Category', exact: true })
  await expect(category).toHaveValue('')
  await category.click()
  const categoryNames = await page.getByRole('option').allTextContents()
  expect(categoryNames).not.toContain('Food & Dining')
  expect(categoryNames).toEqual([...categoryNames].sort((a, b) => a.localeCompare(b)))
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Refund' }).click()
  await expect(page.getByText('Expense category')).toBeVisible()
  const refundCategory = page.getByRole('combobox', { name: 'Expense category', exact: true })
  await refundCategory.click()
  await expect(page.getByRole('option', { name: 'Food & Dining', exact: true })).toHaveCount(0)
  await expect(page.getByRole('option', { name: 'Shopping', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')

  await page.getByRole('button', { name: 'Income' }).click()
  await page.getByRole('combobox', { name: 'Category', exact: true }).click()
  await expect(page.getByRole('option', { name: 'Salary', exact: true })).toBeVisible()
  await expect(page.getByRole('option', { name: 'Shopping', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')

  await page.getByRole('button', { name: 'Transfer', exact: true }).click()
  await page.getByRole('combobox', { name: 'Category', exact: true }).click()
  await expect(page.getByRole('option', { name: 'Money Lent', exact: true })).toBeVisible()

  await page.goto('/money/settings/categories')
  await page.getByRole('button', { name: 'Add category' }).click()
  await expect(page.getByPlaceholder('New expense category')).toBeVisible()
  await page.getByPlaceholder('New expense category').fill('Test category')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(page.getByText('Test category')).toBeVisible()

  await page.goto('/money/expenses/new')
  await page.getByRole('link', { name: 'Add account' }).click()
  await page.getByRole('button', { name: 'Add payment account' }).click()
  await page.getByPlaceholder('e.g., ICICI Bank').fill('Category test account')
  await page.getByRole('button', { name: 'Add Account' }).click()
  await page.goBack()
  await chooseOption(page, 'Paid from', 'Category test account')
  await page.getByLabel('Amount').fill('123.45')
  await page.getByLabel('Title').fill('Test category expense')
  await chooseCategory(page, 'Test category')
  await expect(page.getByRole('button', { name: 'Save Expense' })).toBeEnabled()
  await page.getByRole('button', { name: 'Save Expense' }).click()
  await expect(page).toHaveURL(/\/money\/transactions/)
  await expect(page.getByText('Test category expense')).toBeVisible()

  await page.goto('/money/settings/categories')
  await page.getByRole('button', { name: 'Hide Test category' }).click()
  await expect(page.getByRole('button', { name: 'Show Test category' })).toBeVisible()
  await page.goto('/money/budgets')
  await page.getByRole('tab', { name: 'Allocate' }).click()
  await expect(page.getByRole('button', { name: 'Add budget' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Food & Dining' })).toHaveCount(0)
  await expect(page.getByText('No budget set')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Test category' })).toBeVisible()
  await expect(page.getByRole('heading', { level: 2 }).first()).toHaveText('Test category')
  await expect(page.getByText('₹123.45 spent this month')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Set Test category budget' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Open Test category budget details' }).click()
  await expect(page.getByRole('heading', { name: 'Test category' })).toBeVisible()
  await expect(page.getByText('Category Breakdown')).toBeVisible()
  await expect(page.getByText('This Month', { exact: true })).toBeVisible()
  await expect(page.getByText('This Year', { exact: true })).toBeVisible()
  await expect(page.getByText('₹123.45', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('Remaining')).toBeVisible()
  await expect(page.getByText('—')).toBeVisible()
  // No monthly budget yet, so this category cannot be allocated.
  await expect(page.getByRole('button', { name: 'Set budget' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Budgets page' }).click()
  await page.getByRole('tab', { name: 'Budget', exact: true }).click()
  await page.getByRole('button', { name: 'Set monthly budget' }).click()
  await page.getByPlaceholder('0').fill('500')
  await page.getByRole('button', { name: 'Save monthly budget' }).click()
  await page.getByRole('tab', { name: 'Allocate' }).click()
  await page.getByRole('link', { name: 'Open Test category budget details' }).click()
  await page.getByRole('button', { name: 'Set budget' }).click()
  const budgetAmount = page.getByLabel('Monthly limit', { exact: true })
  const saveBudget = page.getByRole('button', { name: 'Save Test category budget' })
  // Monthly budget is 500: the 20% preset fills 100, the slider and the amount stay in sync.
  await page.getByRole('button', { name: '20%', exact: true }).click()
  await expect(budgetAmount).toHaveValue('100')
  await page.getByRole('slider').focus()
  await page.keyboard.press('ArrowRight')
  await expect(budgetAmount).toHaveValue('105')
  await budgetAmount.fill('100')
  await saveBudget.click()
  await expect(page.getByText('₹100.00', { exact: true })).toBeVisible()
  await expect(
    page.getByRole('img', {
      name: 'Last 6 months spending for Test category compared with monthly budget',
    }),
  ).toBeVisible()
  await expect(page.getByText('Within budget')).toBeVisible()
  await expect(page.getByText('Over budget', { exact: true })).toBeVisible()
  await expect(page.getByText('Budget limit')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Transactions this month' })).toBeVisible()
  await page.getByRole('button', { name: /Expense: Test category expense/ }).click()
  await expect(page.getByRole('heading', { name: 'Test category expense' })).toBeVisible()
  await page.getByRole('link', { name: 'Back to Category' }).click()
  await expect(page.getByRole('heading', { name: 'Transactions this month' })).toBeVisible()
  await page.goto('/money/budgets')
  await expect(page.getByRole('button', { name: 'Delete category Shopping' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Delete category Test category' })).toHaveCount(1)
  await expect(page.getByRole('heading', { name: 'Test category' })).toBeVisible()
  await page.getByRole('link', { name: 'Open Test category budget details' }).click()
  await expect(page.getByText('This Month', { exact: true })).toBeVisible()
  await expect(page.getByText('Remaining')).toBeVisible()
  await expect(page.getByText('Monthly limit')).toBeVisible()
  await expect(page.getByText('₹100.00', { exact: true })).toBeVisible()
  await expect(page.getByText('₹123.45', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('Over budget by')).toBeVisible()
  await expect(page.getByRole('button', { name: /Expense: Test category expense/ })).toBeVisible()
  await page.getByRole('link', { name: 'Back to Budgets' }).click()
  await expect(page.getByRole('heading', { name: 'Test category' })).toBeVisible()
  await expect(page.getByText('Available to spend')).toHaveCount(0)
  await expect(page.getByText('Over budget by')).toBeVisible()
  await expect(page.getByText('Monthly limit')).toBeVisible()
  await expect(page.getByText('100% used')).toBeVisible()
  await page.getByRole('button', { name: 'Delete category Test category' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete category' }).click()
  await expect(page.getByRole('heading', { name: 'Test category' })).toHaveCount(0)
  await page.goto('/money/transactions')
  await expect(page.getByText('Test category expense')).toHaveCount(0)
})
