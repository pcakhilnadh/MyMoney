import { expect, test } from '@playwright/test'
import { chooseOption, fakeSignIn } from './helpers'

test('add, list, budget, delete — works offline', async ({ page, context }) => {
  await page.route('**/auth/refresh', (route) => route.abort())
  await page.route('**/auth/login', (route) => route.abort())
  await fakeSignIn(page)
  await page.goto('/money/home')
  await expect(page.getByText('Spent this month')).toBeVisible()
  await context.setOffline(true) // local-first: no network needed from here

  await page.getByRole('link', { name: 'Add expense' }).click()
  await page.getByRole('link', { name: 'Add account' }).click()
  await page.getByRole('button', { name: 'Add payment account' }).click()
  await page.getByPlaceholder('e.g., ICICI Bank').fill('Everyday')
  await page.getByRole('button', { name: 'Add Account' }).click()
  await page.goBack()
  await chooseOption(page, 'Paid from', 'Everyday')
  await expect(page.getByLabel('Paid from')).toContainText('Everyday')
  await page.getByLabel('Amount').pressSequentially('250.50')
  await expect(page.getByLabel('Amount')).toHaveValue('250.50')
  await page.getByPlaceholder('Title').fill('Lunch')
  await page.getByLabel('Merchant').fill('Amazon')
  await page.getByLabel('Long Description').fill('Lunch during a work break')
  await expect(page.getByRole('button', { name: 'Save Expense' })).toBeDisabled()
  await page.getByRole('button', { name: 'Food & Dining', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save Expense' })).toBeEnabled()
  await page.getByRole('button', { name: 'Save Expense' }).click()

  await expect(page).toHaveURL(/\/money\/transactions/)
  await expect(page.getByText('Lunch', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Expense: Lunch/ }).click()
  await expect(page.getByText('Amazon')).toBeVisible()
  await expect(page.getByText('Lunch during a work break')).toBeVisible()
  await expect(page.getByText('₹250.50')).toBeVisible()
  await page.getByRole('link', { name: '← Transactions' }).click()
  await page.getByRole('button', { name: 'Add transaction' }).click()
  await expect(page).toHaveURL(/\/money\/expenses\/new/)
  await page.getByLabel('Merchant').click()
  await expect(page.getByRole('option', { name: 'Amazon', exact: true })).toBeVisible()
  await page.goBack()
  await page.getByPlaceholder('Search transactions or merchants').fill('zzz')
  await expect(page.getByText('No transactions yet')).toBeVisible()
  await page.getByPlaceholder('Search transactions or merchants').fill('lun')
  await expect(page.getByText('Lunch', { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Home' }).click()
  await expect(page.getByText('₹250.50').first()).toBeVisible()

  await page.getByRole('link', { name: 'Settings' }).click()
  await page.getByRole('link', { name: 'Budgets' }).click()
  await page.getByRole('button', { name: 'Set Food & Dining budget' }).click()
  await expect(page.getByPlaceholder('Name (optional)')).toHaveCount(0)
  await page.getByPlaceholder('0').fill('1000')
  await page.getByRole('button', { name: 'Add Budget' }).click()
  await expect(page.getByText('₹749.50')).toBeVisible()
  await expect(page.getByText('₹250.50 spent')).toBeVisible()
  await expect(page.getByText('₹1,000.00', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Delete Food & Dining budget' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Delete category Food & Dining' })).toHaveCount(0)
  await expect(page.getByText('Monthly budget')).toHaveCount(0)
  await expect(page.getByText('On track')).toHaveCount(0)

  await page.getByRole('button', { name: 'Edit Food & Dining' }).click()
  await page.getByPlaceholder('0').fill('2000')
  await page.getByRole('button', { name: 'Save Budget' }).click()
  await expect(page.getByText('₹1,749.50')).toBeVisible()

  await page.getByRole('button', { name: 'Edit Food & Dining' }).click()
  page.once('dialog', async (dialog) => {
    expect(dialog.type()).toBe('confirm')
    expect(dialog.message()).toContain('Food & Dining')
    await dialog.accept()
  })
  await page.getByRole('button', { name: 'Delete budget' }).click()
  await expect(page.getByText('₹1,749.50')).not.toBeVisible()

  await page.getByRole('link', { name: 'Settings' }).click()
  await page.getByRole('link', { name: 'Payment Account' }).click()
  await page.getByRole('heading', { name: 'Everyday' }).click()
  await expect(page.getByText('Lunch', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Expense: Lunch/ })).toBeVisible()
  await expect(page.getByText('₹250.50').first()).toBeVisible()
  await page.getByRole('button', { name: /Expense: Lunch/ }).click()
  await expect(page.getByText('Amazon')).toBeVisible()
  await page.getByRole('link', { name: '← Account' }).click()

  await page.getByRole('link', { name: 'Transactions' }).click()
  await page.getByRole('button', { name: /Expense: Lunch/ }).click()
  page.once('dialog', async (dialog) => {
    expect(dialog.type()).toBe('confirm')
    expect(dialog.message()).toContain('Lunch')
    await dialog.accept()
  })
  await page.getByRole('button', { name: 'Delete transaction' }).click()
  await expect(page.getByText('No transactions yet')).toBeVisible()
})

test('capture income and transfers from the add-transaction flow', async ({ page, context }) => {
  await page.route('**/auth/refresh', (route) => route.abort())
  await page.route('**/auth/login', (route) => route.abort())
  await fakeSignIn(page)
  await page.goto('/money/home')
  await context.setOffline(true)

  await page.getByRole('link', { name: 'Add expense' }).click()
  await page.getByRole('link', { name: 'Add account' }).click()
  await page.getByRole('button', { name: 'Add payment account' }).click()
  await page.getByPlaceholder('e.g., ICICI Bank').fill('Checking')
  await page.getByRole('button', { name: 'Add Account' }).click()
  await expect(page.getByRole('heading', { name: 'Checking' })).toBeVisible()
  await page.getByRole('button', { name: 'Add payment account' }).click()
  await page.getByPlaceholder('e.g., ICICI Bank').fill('Savings')
  await page.getByRole('button', { name: 'Add Account' }).click()
  await expect(page.getByRole('heading', { name: 'Savings' })).toBeVisible()
  await page.getByRole('button', { name: 'Add payment account' }).click()
  await page.getByPlaceholder('e.g., ICICI Bank').fill('Loan — Alex')
  await chooseOption(page, 'Account type', 'Loan')
  await expect(
    page.getByText(/For money you owe \(loans, lines of credit\)\. Record loan disbursals/),
  ).toBeVisible()
  await page.getByRole('button', { name: 'Add Account' }).click()
  await expect(page.getByRole('heading', { name: 'Loan — Alex' })).toBeVisible()
  await page.getByRole('button', { name: 'Add payment account' }).click()
  await page.getByPlaceholder('e.g., ICICI Bank').fill('Money lent — Sam')
  await chooseOption(page, 'Account type', 'Asset (Money Owed to You)')
  await expect(
    page.getByText(/Record lending as a transfer from your bank or cash account/),
  ).toBeVisible()
  await page.getByRole('button', { name: 'Add Account' }).click()
  await expect(page.getByRole('heading', { name: 'Money lent — Sam' })).toBeVisible()

  await page.getByRole('link', { name: 'Add expense' }).click()
  await page.getByRole('button', { name: 'Income' }).click()
  await page.getByPlaceholder('Title').fill('Payday')
  await page.getByRole('button', { name: 'Salary' }).click()
  await page.getByPlaceholder('0').fill('2500')
  await page.getByLabel('Received into').click()
  await expect(page.getByRole('option')).toHaveText([
    'Checking',
    'Loan — Alex',
    'Money lent — Sam',
    'Savings',
  ])
  await page.getByRole('option', { name: 'Checking', exact: true }).click()
  await expect(page.getByLabel('Received into')).toContainText('Checking')
  await page.getByRole('button', { name: 'Save Income' }).click()
  await expect(page.getByText('Payday')).toBeVisible()

  await page.getByRole('link', { name: 'Add expense' }).click()
  await page.getByRole('button', { name: 'Refund', exact: true }).click()
  await page.getByRole('button', { name: 'Food & Dining', exact: true }).click()
  await page.getByPlaceholder('Title').fill('Returned meal')
  await page.getByPlaceholder('0').fill('250')
  await chooseOption(page, 'Received into', 'Checking')
  await expect(page.getByLabel('Received into')).toContainText('Checking')
  await page.getByRole('button', { name: 'Save Refund' }).click()
  await expect(page.getByText('Returned meal')).toBeVisible()

  await page.getByRole('link', { name: 'Add expense' }).click()
  await page.getByRole('button', { name: 'Transfer', exact: true }).click()
  await page.getByRole('button', { name: 'Savings & Investments' }).click()
  await page.getByPlaceholder('Title').fill('Move to savings')
  await page.getByPlaceholder('0').fill('1000')
  await page.getByLabel('From account').click()
  await expect(page.getByRole('option')).toHaveText([
    'Checking',
    'Loan — Alex',
    'Money lent — Sam',
    'Savings',
  ])
  await page.getByRole('option', { name: 'Checking', exact: true }).click()
  await expect(page.getByLabel('From account')).toContainText('Checking')
  await page.getByLabel('To account').click()
  await expect(page.getByRole('option')).toHaveText(['Loan — Alex', 'Money lent — Sam', 'Savings'])
  await page.getByRole('option', { name: 'Savings', exact: true }).click()
  await expect(page.getByLabel('To account')).toContainText('Savings')
  await page.getByRole('button', { name: 'Save Transfer' }).click()
  await expect(page.getByText('Move to savings')).toBeVisible()

  await page.getByRole('link', { name: 'Add expense' }).click()
  await page.getByRole('button', { name: 'Transfer', exact: true }).click()
  await page.getByRole('button', { name: 'Money Borrow' }).click()
  await page.getByPlaceholder('Title').fill('Borrow from Alex')
  await page.getByPlaceholder('0').fill('500')
  await chooseOption(page, 'From account', 'Loan — Alex')
  await chooseOption(page, 'To account', 'Checking')
  await page.getByRole('button', { name: 'Save Transfer' }).click()

  await page.getByRole('link', { name: 'Add expense' }).click()
  await page.getByRole('button', { name: 'Transfer', exact: true }).click()
  await page.getByRole('button', { name: 'Loan Repayment' }).click()
  await page.getByPlaceholder('Title').fill('Repay Alex')
  await page.getByPlaceholder('0').fill('100')
  await chooseOption(page, 'From account', 'Checking')
  await chooseOption(page, 'To account', 'Loan — Alex')
  await page.getByRole('button', { name: 'Save Transfer' }).click()

  await page.getByRole('link', { name: 'Add expense' }).click()
  await page.getByRole('button', { name: 'Transfer', exact: true }).click()
  await page.getByRole('button', { name: 'Money Lent' }).click()
  await page.getByPlaceholder('Title').fill('Lend to Sam')
  await page.getByPlaceholder('0').fill('300')
  await chooseOption(page, 'From account', 'Checking')
  await chooseOption(page, 'To account', 'Money lent — Sam')
  await page.getByRole('button', { name: 'Save Transfer' }).click()

  await page.getByRole('link', { name: 'Add expense' }).click()
  await page.getByRole('button', { name: 'Transfer', exact: true }).click()
  await page.getByRole('button', { name: 'Loan Collection' }).click()
  await page.getByPlaceholder('Title').fill('Sam repaid')
  await page.getByPlaceholder('0').fill('50')
  await chooseOption(page, 'From account', 'Money lent — Sam')
  await chooseOption(page, 'To account', 'Checking')
  await page.getByRole('button', { name: 'Save Transfer' }).click()

  await page.getByRole('link', { name: 'Settings' }).click()
  await page.getByRole('link', { name: 'Payment Account' }).click()
  await page.getByRole('heading', { name: 'Loan — Alex' }).click()
  await expect(page.getByText('Amount owed')).toBeVisible()
  await expect(page.getByText('₹400.00')).toBeVisible()
  await page.getByRole('link', { name: '← Payment Account' }).click()
  await page.getByRole('heading', { name: 'Money lent — Sam' }).click()
  await expect(page.getByText('Owed to you', { exact: true })).toBeVisible()
  await expect(page.getByText('₹250.00')).toBeVisible()
})
